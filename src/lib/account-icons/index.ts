import { getImageUrl } from "~/lib/image-url";
import brandData from "./brands.json";

/**
 * The mark beside an account (Wealth rows, account pickers). The stored shape
 * is `{ kind, value }`; null keeps the default glyph for the account's type.
 *   BRAND     value is a bundled logo's slug
 *   MONOGRAM  value is an avatar palette slot; the mark is the name's first letter
 *   IMAGE     value is the uploaded file's path in the upload store
 * Shared by the server (validation) and the client (drawing).
 */
export type AccountIconKind = "BRAND" | "MONOGRAM" | "IMAGE";
export type AccountIcon = { kind: AccountIconKind; value: string };

export type Brand = {
	slug: string;
	title: string;
	/** The logo's own color, six hex digits. Asset data, not a UI token. */
	hex: string;
	/** The 24 by 24 SVG path. */
	path: string;
};

/** The finance subset of Simple Icons (CC0), generated by scripts/gen-account-icons.mjs. */
export const BRANDS: readonly Brand[] = brandData;

const BY_SLUG = new Map(BRANDS.map((b) => [b.slug, b]));

export const brandBySlug = (slug: string): Brand | undefined =>
	BY_SLUG.get(slug);

/** The avatar palette's slots: the colors people already wear (GUIDELINE §2.2). */
export const MONOGRAM_SLOTS = [
	"avatar-1",
	"avatar-2",
	"avatar-3",
	"avatar-4",
	"avatar-5",
	"avatar-6",
	"avatar-7",
	"avatar-8",
] as const;
export type MonogramSlot = (typeof MONOGRAM_SLOTS)[number];

/** Tailwind needs whole class names, so the slots are spelled out. */
export const MONOGRAM_BG: Record<MonogramSlot, string> = {
	"avatar-1": "bg-avatar-1",
	"avatar-2": "bg-avatar-2",
	"avatar-3": "bg-avatar-3",
	"avatar-4": "bg-avatar-4",
	"avatar-5": "bg-avatar-5",
	"avatar-6": "bg-avatar-6",
	"avatar-7": "bg-avatar-7",
	"avatar-8": "bg-avatar-8",
};

export const isMonogramSlot = (value: string): value is MonogramSlot =>
	(MONOGRAM_SLOTS as readonly string[]).includes(value);

/** Uploads are re-encoded to WebP and named by the account and the time. */
const IMAGE_PATH = /^accounts\/[A-Za-z0-9_-]+\.webp$/;

/** Whether a stored or sent icon is one the app can draw. */
export function isAccountIcon(
	kind: string | null | undefined,
	value: string | null | undefined,
): boolean {
	if (!kind || !value) return false;
	if (kind === "BRAND") return BY_SLUG.has(value);
	if (kind === "MONOGRAM") return isMonogramSlot(value);
	if (kind === "IMAGE") return IMAGE_PATH.test(value);
	return false;
}

/** The letter on a monogram: the name's first letter or digit, upper case. */
export function monogramLetter(name: string): string {
	const first = [...name.trim()].find((ch) => /[\p{L}\p{N}]/u.test(ch));
	return (first ?? "?").toLocaleUpperCase();
}

/** Perceived lightness of a hex color, 0 (black) to 1 (white). */
function lightness(hex: string): number {
	const n = Number.parseInt(hex, 16);
	const channel = (shift: number) => {
		const c = ((n >> shift) & 255) / 255;
		return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
	};
	return 0.2126 * channel(16) + 0.7152 * channel(8) + 0.0722 * channel(0);
}

/**
 * Whether a logo can be drawn in its own color on both themes' tiles. A mark
 * that is nearly black or nearly white would vanish on one of them, so it is
 * drawn in the text color instead (a one-color logo stays recognizable).
 */
export function brandUsesOwnColor(hex: string): boolean {
	const l = lightness(hex);
	return l >= 0.05 && l <= 0.7;
}

/**
 * A stored icon as the readers give it (the page, the API): the image's value
 * is its URL. A row whose icon the app cannot draw (a logo since removed)
 * reads as none.
 */
export function iconOf(row: {
	iconKind?: AccountIconKind | null;
	iconValue?: string | null;
}): AccountIcon | null {
	const { iconKind: kind, iconValue: value } = row;
	if (!kind || !value || !isAccountIcon(kind, value)) return null;
	return kind === "IMAGE"
		? { kind, value: getImageUrl(value) ?? value }
		: { kind, value };
}
