/**
 * The project CSVs: its expenses, one billing period with its settlement
 * plan, and the settlement plan alone. Amounts are read exactly and the plan
 * comes from the project summary's matcher on minor units, so these files
 * agree with the Summary tab to the last digit.
 */
import { dayKey } from "@retrospend/domain/time-zone";
import { TRPCError } from "@trpc/server";
import { csvMeta, generateCsv } from "~/lib/csv";
import type { DecimalLike } from "~/server/services/envelope/types";
import { fetchProjectLedger } from "~/server/services/project/ledger";
import {
	type ProjectNumbers,
	summarizeLedger,
} from "~/server/services/project/summary";
import { requireProjectRole } from "~/server/services/shared-expenses/project-permissions";
import type { PrismaClient } from "~prisma";
import { amountText, exactCell, minorCell, totalsText } from "./amounts";
import { type CsvDocument, type ExportContext, slug } from "./context";
import {
	fetchEditCounts,
	nameOf,
	resolveParticipantNames,
	txStatus,
} from "./names";

/** The project's plan: fewest transfers per currency, exact. */
export async function projectNumbers(
	db: PrismaClient,
	projectId: string,
	periodId?: string,
): Promise<ProjectNumbers> {
	const [ledger, members] = await Promise.all([
		fetchProjectLedger(db, projectId, periodId),
		db.projectParticipant.findMany({
			where: { projectId },
			select: { participantType: true, participantId: true },
			orderBy: { joinedAt: "asc" },
		}),
	]);
	return summarizeLedger(ledger, members);
}

async function viewerOf(ctx: ExportContext, projectId: string) {
	await requireProjectRole(ctx.db, projectId, "user", ctx.userId, "VIEWER");
}

const SETTLEMENT_HEADERS = ["From", "To", "Amount", "Currency"];
const NO_SETTLEMENTS = "From,To,Amount,Currency\n(No settlements required)\n";

async function planRows(
	db: PrismaClient,
	numbers: ProjectNumbers,
): Promise<unknown[][]> {
	const names = await resolveParticipantNames(
		db,
		numbers.transfers.flatMap((t) => [t.from, t.to]),
	);
	return numbers.transfers.map((t) => [
		nameOf(names, t.from),
		nameOf(names, t.to),
		minorCell(t.amount.minor, t.amount.currency),
		t.amount.currency,
	]);
}

const splitDetails = (
	tx: {
		currency: string;
		splitParticipants: ReadonlyArray<{
			participantType: string;
			participantId: string;
			shareAmount: DecimalLike;
		}>;
	},
	names: ReadonlyMap<string, string>,
	withCurrency: boolean,
) =>
	tx.splitParticipants
		.map((sp) => {
			const share = amountText(sp.shareAmount, tx.currency);
			return `${nameOf(names, sp)}: ${share}${withCurrency ? ` ${tx.currency}` : ""}`;
		})
		.join("; ");

const expenseInclude = {
	category: { select: { name: true } },
	splitParticipants: {
		select: {
			participantType: true,
			participantId: true,
			shareAmount: true,
			verificationStatus: true,
		},
	},
} as const;

/**
 * Every shared expense of a project (or one billing period) as a CSV.
 * Split Details is one string per row: "Alice: 30.00 USD; Bob: 30.00 USD".
 */
export async function exportProjectExpenses(
	ctx: ExportContext,
	input: { projectId: string; periodId?: string },
): Promise<CsvDocument> {
	await viewerOf(ctx, input.projectId);
	const project = await ctx.db.project.findUniqueOrThrow({
		where: { id: input.projectId },
		select: { name: true },
	});
	const transactions = await ctx.db.sharedTransaction.findMany({
		where: {
			projectId: input.projectId,
			...(input.periodId ? { billingPeriodId: input.periodId } : {}),
		},
		include: expenseInclude,
		orderBy: { date: "desc" },
	});
	const names = await resolveParticipantNames(
		ctx.db,
		transactions.flatMap((tx) => [
			{ participantType: tx.paidByType, participantId: tx.paidById },
			...tx.splitParticipants,
		]),
	);
	const editCounts = await fetchEditCounts(transactions.map((tx) => tx.id));

	const headers = [
		"Date",
		"Description",
		"Amount",
		"Currency",
		"Category",
		"Paid By",
		"Split Mode",
		"Split Details",
		"Status",
		"Edits",
	];
	const rows = transactions.map((tx) => [
		tx.date,
		tx.description,
		exactCell(tx.amount),
		tx.currency,
		tx.category?.name ?? "",
		nameOf(names, {
			participantType: tx.paidByType,
			participantId: tx.paidById,
		}),
		tx.splitMode,
		splitDetails(tx, names, true),
		txStatus(tx.isLocked, tx.splitParticipants),
		editCounts.get(tx.id) ?? 0,
	]);

	const today = dayKey(new Date(), ctx.timeZone);
	const meta = csvMeta([
		"Generated by Retrospend",
		`Export Date: ${today}`,
		`Project: ${project.name}${input.periodId ? " (period-filtered)" : ""}`,
		`Total Expenses: ${transactions.length}`,
		"",
	]);
	return {
		csv: meta + generateCsv(headers, rows),
		filename: `${slug(project.name, 40)}-expenses-${today}.csv`,
	};
}

/**
 * One billing period: its expenses, then the minimum payments that settle
 * the project's books against them.
 */
export async function exportBillingPeriodSummary(
	ctx: ExportContext,
	input: { projectId: string; periodId: string },
): Promise<CsvDocument> {
	await viewerOf(ctx, input.projectId);
	const [project, period] = await Promise.all([
		ctx.db.project.findUniqueOrThrow({
			where: { id: input.projectId },
			select: { name: true, primaryCurrency: true },
		}),
		ctx.db.billingPeriod.findUnique({
			where: { id: input.periodId },
			include: {
				sharedTransactions: {
					include: expenseInclude,
					orderBy: { date: "desc" },
				},
			},
		}),
	]);
	if (!period || period.projectId !== input.projectId) {
		throw new TRPCError({
			code: "NOT_FOUND",
			message: "Billing period not found",
		});
	}
	const transactions = period.sharedTransactions;
	const names = await resolveParticipantNames(
		ctx.db,
		transactions.flatMap((tx) => [
			{ participantType: tx.paidByType, participantId: tx.paidById },
			...tx.splitParticipants,
		]),
	);
	const numbers = await projectNumbers(ctx.db, input.projectId, input.periodId);
	const editCounts = await fetchEditCounts(transactions.map((tx) => tx.id));

	const today = dayKey(new Date(), ctx.timeZone);
	const range = `${period.startDate.toISOString().slice(0, 10)} to ${period.endDate.toISOString().slice(0, 10)}`;
	const meta = csvMeta([
		"Generated by Retrospend",
		`Export Date: ${today}`,
		`Project: ${project.name}`,
		`Period: ${period.label}`,
		`Date Range: ${range}`,
		`Total Spent: ${totalsText(transactions, project.primaryCurrency).join("; ")}`,
		"",
	]);

	const expenseHeaders = [
		"Date",
		"Description",
		"Amount",
		"Currency",
		"Category",
		"Paid By",
		"Split Details",
		"Status",
		"Edits",
	];
	const expenseRows = transactions.map((tx) => [
		tx.date,
		tx.description,
		exactCell(tx.amount),
		tx.currency,
		tx.category?.name ?? "",
		nameOf(names, {
			participantType: tx.paidByType,
			participantId: tx.paidById,
		}),
		splitDetails(tx, names, false),
		txStatus(tx.isLocked, tx.splitParticipants),
		editCounts.get(tx.id) ?? 0,
	]);
	const settlementRows = await planRows(ctx.db, numbers);

	const csv =
		`${meta}EXPENSES\n${generateCsv(expenseHeaders, expenseRows)}\n\nSETTLEMENT PLAN\n` +
		(settlementRows.length > 0
			? generateCsv(SETTLEMENT_HEADERS, settlementRows)
			: NO_SETTLEMENTS);
	return {
		csv,
		filename: `${slug(project.name, 30)}-${slug(period.label, 25)}-${today}.csv`,
	};
}

/** Who pays whom to settle a project (or one billing period): From, To, Amount, Currency. */
export async function exportSettlementPlan(
	ctx: ExportContext,
	input: { projectId: string; periodId?: string },
): Promise<CsvDocument> {
	await viewerOf(ctx, input.projectId);
	const project = await ctx.db.project.findUniqueOrThrow({
		where: { id: input.projectId },
		select: { name: true },
	});
	const numbers = await projectNumbers(ctx.db, input.projectId, input.periodId);
	const rows = await planRows(ctx.db, numbers);

	const today = dayKey(new Date(), ctx.timeZone);
	const meta = csvMeta([
		"Generated by Retrospend",
		`Export Date: ${today}`,
		`Project: ${project.name}${input.periodId ? " (period-scoped)" : ""}`,
		"",
	]);
	return {
		csv:
			meta +
			(rows.length > 0
				? generateCsv(SETTLEMENT_HEADERS, rows)
				: NO_SETTLEMENTS),
		filename: `${slug(project.name, 40)}-settlements-${today}.csv`,
	};
}
