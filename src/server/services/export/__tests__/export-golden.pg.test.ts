describe("PDFs", () => {
	it("the project PDF has one total, category row and balance row per currency", async () => {
		const out = await ana.exportProjectPdf({ projectId: book.project.id });
		expect(steady(out.filename)).toBe("cordoba-summary-<day>.pdf");
		const runs = textOf(out.pdf);

		expect(between(runs, "Summary", "Category Breakdown")).toEqual([
			"Total Spent: 1297567.89 ARS; 100.00 BRL; 0.004 ETH; 50.00 USD",
			"Expenses: 6",
			"Budget: 5000000.00 ARS",
		]);
		expect(between(runs, "Category Breakdown", "Participant Balances")).toEqual(
			[
				...["Category", "Count", "Total", "Currency"],
				...["Food", "1", "1234567.89", "ARS"],
				...["Uncategorized", "2", "63000.00", "ARS"],
				...["Uncategorized", "1", "100.00", "BRL"],
				...["Uncategorized", "1", "0.004", "ETH"],
				...["Uncategorized", "1", "50.00", "USD"],
			],
		);
		const balances = between(runs, "Participant Balances", "Settlement Plan");
		expect(balances.slice(0, 5)).toEqual([
			"Name",
			"Currency",
			"Paid",
			"Fair Share",
			"Net Balance",
		]);
		const rows = balances.slice(5);
		const row = (name: string, currency: string) => {
			const at = rows.findIndex(
				(_, i) => rows[i] === name && rows[i + 1] === currency,
			);
			return rows.slice(at, at + 5);
		};
		expect(row("Ana", "ARS")).toEqual([
			"Ana",
			"ARS",
			"1297567.89",
			"442522.63",
			"+755045.26",
		]);
		expect(row("Ana", "BRL")).toEqual([
			"Ana",
			"BRL",
			"0.00",
			"33.33",
			"-43.33",
		]);
		expect(row("Ben", "BRL")).toEqual([
			"Ben",
			"BRL",
			"100.00",
			"33.33",
			"+66.67",
		]);
		expect(row("Ben", "ETH")).toEqual(["Ben", "ETH", "0", "0.002", "-0.002"]);
		expect(row("Cam", "USD")).toEqual([
			"Cam",
			"USD",
			"50.00",
			"30.00",
			"+20.00",
		]);
		expect(row("Sam", "ARS")).toEqual([
			"Sam",
			"ARS",
			"0.00",
			"2000.00",
			"-2000.00",
		]);
	});

	it("the person PDF rounds the Tapas tie to the even neighbor and keeps ETH", async () => {
		const out = await ana.exportPersonPdf(ben());
		const runs = textOf(out.pdf);

		expect(between(runs, "Balance Summary", "Project Breakdown")).toEqual([
			...["Currency", "Amount", "Direction"],
			...["ARS", "341522.63", "Ben owes you"],
			...["BRL", "30.65", "You owe Ben"],
			...["ETH", "0.002", "Ben owes you"],
			...["EUR", "6.25", "Ben owes you"],
		]);
		expect(between(runs, "Category Breakdown", "Expenses")).toEqual([
			...["Category", "Count", "Total", "Currency"],
			...["Food", "1", "1234567.89", "ARS"],
			...["Uncategorized", "1", "60000.00", "ARS"],
			...["Uncategorized", "2", "105.35", "BRL"],
			...["Uncategorized", "1", "0.004", "ETH"],
			...["Uncategorized", "1", "12.50", "EUR"],
		]);
		const expenses = between(runs, "Expenses", "");
		// Tapas: amount 5.35, shares 2.675 shown as 2.68; Gas: 0.004 ETH, 0.002 each.
		const tapas = expenses.indexOf("Tapas");
		expect(expenses.slice(tapas, tapas + 6)).toEqual([
			"Tapas",
			"5.35",
			"BRL",
			"Ana",
			"2.68",
			"2.68",
		]);
		const gas = expenses.indexOf("Gas");
		expect(expenses.slice(gas, gas + 7)).toEqual([
			"Gas",
			"0.004",
			"ETH",
			"Ana",
			"0.002",
			"0.002",
			"Cordoba",
		]);
	});
});

describe("account zip", () => {
	it("writes decimals as numbers: a debt stays negative, a satoshi stays plain", async () => {
		const out = await ana.allData();
		expect(steady(out.filename)).toBe("user-data-<day>.zip");
		const zip = await JSZip.loadAsync(Buffer.from(out.zipData, "base64"));
		const file = async (name: string) =>
			(await zip.files[name]?.async("string")) ?? "";
		const cells = (csv: string) =>
			csv.split("\n").map((row) => row.split(",").slice(1));

		expect(cells(await file("asset_accounts.csv"))).toEqual([
			[
				"name",
				"type",
				"currency",
				"balance",
				"exchangeRate",
				"exchangeRateType",
				"isLiquid",
				"interestRate",
				"minimumPayment",
				"dueDate",
				"closedAt",
				"createdAt",
				"updatedAt",
			],
			expect.arrayContaining(["Visa", "ARS", "-150000.25"]),
			expect.arrayContaining(["Wallet", "ETH", "0.00000001", "0.125"]),
		]);
		expect(await file("asset_snapshots.csv")).toContain(",-90000.1,-60.02,");
		expect(await file("expenses.csv")).toContain(
			",Alquiler,1500000.5,ARS,1499.5,1000.33,",
		);
		expect(await file("recurring_templates.csv")).toContain(
			",Gym,25000.75,ARS,",
		);
	});
});
