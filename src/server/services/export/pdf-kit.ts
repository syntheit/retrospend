import { dayKey } from "@retrospend/domain/time-zone";
import PDFDocument from "pdfkit";

/**
 * Page furniture the export PDFs share: A4 margins, section headers,
 * tables and the page footer. The documents hand it text that is already
 * formatted; nothing here touches an amount.
 */

export const MARGIN = 50;
export const MARGIN_BOTTOM = 70; // extra space reserved for footer
export const PAGE_WIDTH = 595.28; // A4
export const PAGE_HEIGHT = 841.89;
export const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2;
export const FONT_SIZE_TITLE = 20;
export const FONT_SIZE_SECTION = 13;
export const FONT_SIZE_BODY = 9;
export const FONT_SIZE_SMALL = 8;
export const ROW_HEIGHT = 18;
export const HEADER_ROW_HEIGHT = 20;
export const SECTION_GAP = 24;
export const COLOR_PRIMARY = "#1a1a1a";
export const COLOR_SECONDARY = "#666666";
export const COLOR_HEADER_BG = "#f5f5f5";
export const COLOR_BORDER = "#e0e0e0";

/**
 * Runs `draw` on a fresh A4 document and resolves with the finished bytes.
 */
export function renderPdf(
	draw: (doc: PDFKit.PDFDocument) => void,
): Promise<Buffer> {
	return new Promise((resolve, reject) => {
		const doc = new PDFDocument({
			size: "A4",
			margins: {
				top: MARGIN,
				bottom: MARGIN_BOTTOM,
				left: MARGIN,
				right: MARGIN,
			},
			bufferPages: true,
		});
		const chunks: Buffer[] = [];
		doc.on("data", (chunk: Buffer) => chunks.push(chunk));
		doc.on("end", () => resolve(Buffer.concat(chunks)));
		doc.on("error", reject);
		draw(doc);
		doc.end();
	});
}

// ── Helpers ─────────────────────────────────────────────────────────────────

export function drawSectionHeader(
	doc: PDFKit.PDFDocument,
	title: string,
	y: number,
): number {
	doc
		.fontSize(FONT_SIZE_SECTION)
		.font("Helvetica-Bold")
		.fillColor(COLOR_PRIMARY)
		.text(title, MARGIN, y);
	const lineY = y + FONT_SIZE_SECTION + 4;
	doc
		.moveTo(MARGIN, lineY)
		.lineTo(MARGIN + CONTENT_WIDTH, lineY)
		.strokeColor(COLOR_BORDER)
		.lineWidth(0.5)
		.stroke();
	return lineY + 8;
}

export interface TableColumn {
	header: string;
	width: number;
	align?: "left" | "right" | "center";
}

export function drawTable(
	doc: PDFKit.PDFDocument,
	columns: TableColumn[],
	rows: string[][],
	startY: number,
): number {
	let y = startY;

	// Header row
	if (y + HEADER_ROW_HEIGHT > PAGE_HEIGHT - MARGIN_BOTTOM) {
		doc.addPage();
		y = MARGIN;
	}

	doc.rect(MARGIN, y, CONTENT_WIDTH, HEADER_ROW_HEIGHT).fill(COLOR_HEADER_BG);

	let x = MARGIN;
	for (const col of columns) {
		doc
			.fontSize(FONT_SIZE_SMALL)
			.font("Helvetica-Bold")
			.fillColor(COLOR_PRIMARY)
			.text(col.header, x + 4, y + 5, {
				width: col.width - 8,
				align: col.align ?? "left",
				lineBreak: false,
			});
		x += col.width;
	}

	y += HEADER_ROW_HEIGHT;

	// Data rows
	for (const row of rows) {
		if (y + ROW_HEIGHT > PAGE_HEIGHT - MARGIN_BOTTOM) {
			doc.addPage();
			y = MARGIN;
		}

		// Subtle border
		doc
			.moveTo(MARGIN, y + ROW_HEIGHT)
			.lineTo(MARGIN + CONTENT_WIDTH, y + ROW_HEIGHT)
			.strokeColor(COLOR_BORDER)
			.lineWidth(0.25)
			.stroke();

		x = MARGIN;
		for (let i = 0; i < columns.length; i++) {
			const col = columns[i];
			if (!col) continue;
			const cellText = row[i] ?? "";
			doc
				.fontSize(FONT_SIZE_BODY)
				.font("Helvetica")
				.fillColor(COLOR_PRIMARY)
				.text(cellText, x + 4, y + 4, {
					width: col.width - 8,
					align: col.align ?? "left",
					lineBreak: false,
				});
			x += col.width;
		}

		y += ROW_HEIGHT;
	}

	return y;
}

export function addFooter(doc: PDFKit.PDFDocument, timeZone?: string) {
	const generatedOn = dayKey(new Date(), timeZone);
	const pageRange = doc.bufferedPageRange();
	const footerY = PAGE_HEIGHT - MARGIN_BOTTOM + 20;
	for (let i = 0; i < pageRange.count; i++) {
		doc.switchToPage(i);
		const savedBottom = doc.page.margins.bottom;
		doc.page.margins.bottom = 0;
		doc
			.fontSize(7)
			.font("Helvetica")
			.fillColor(COLOR_SECONDARY)
			.text(
				`Generated by Retrospend on ${generatedOn}  |  Page ${i + 1} of ${pageRange.count}`,
				MARGIN,
				footerY,
				{ width: CONTENT_WIDTH, align: "center", lineBreak: false },
			);
		doc.page.margins.bottom = savedBottom;
	}
}
