/** The person CSVs: every expense two people share, and what is open between them. */
import { dayKey } from "@retrospend/domain/time-zone";
import { csvMeta, generateCsv } from "~/lib/csv";
import { exactCell } from "./amounts";
import { type CsvDocument, type ExportContext, slug } from "./context";
import {
	fetchEditCounts,
	nameOf,
	resolveParticipantNames,
	txStatus,
} from "./names";
import {
	balanceText,
	directionText,
	noSharedExpenses,
	type PersonRef,
	pairBalances,
	sharedWith,
} from "./person";

/** Date, description, amounts, the user's share and theirs, project and status. */
export async function exportPersonHistory(
	ctx: ExportContext,
	them: PersonRef,
): Promise<CsvDocument> {
	const where = await sharedWith(ctx.db, them);
	if ((await ctx.db.sharedTransaction.count({ where })) === 0) {
		throw noSharedExpenses();
	}
	const transactions = await ctx.db.sharedTransaction.findMany({
		where,
		include: {
			category: { select: { name: true } },
			splitParticipants: {
				select: {
					participantType: true,
					participantId: true,
					shareAmount: true,
					verificationStatus: true,
				},
			},
		},
		orderBy: { date: "desc" },
	});

	const names = await resolveParticipantNames(ctx.db, [
		...transactions.map((tx) => ({
			participantType: tx.paidByType,
			participantId: tx.paidById,
		})),
		them,
	]);
	const projectIds = [
		...new Set(transactions.flatMap((t) => (t.projectId ? [t.projectId] : []))),
	];
	const projects =
		projectIds.length > 0
			? await ctx.db.project.findMany({
					where: { id: { in: projectIds } },
					select: { id: true, name: true },
				})
			: [];
	const projectName = new Map(projects.map((p) => [p.id, p.name]));
	const theirName = nameOf(names, them);
	const editCounts = await fetchEditCounts(transactions.map((tx) => tx.id));

	const headers = [
		"Date",
		"Description",
		"Total Amount",
		"Currency",
		"Category",
		"Paid By",
		"Your Share",
		"Their Share",
		"Project",
		"Status",
		"Edits",
	];
	const rows = transactions.map((tx) => {
		const mine = tx.splitParticipants.find(
			(sp) => sp.participantType === "user" && sp.participantId === ctx.userId,
		);
		const theirs = tx.splitParticipants.find(
			(sp) =>
				sp.participantType === them.participantType &&
				sp.participantId === them.participantId,
		);
		return [
			tx.date,
			tx.description,
			exactCell(tx.amount),
			tx.currency,
			tx.category?.name ?? "",
			nameOf(names, {
				participantType: tx.paidByType,
				participantId: tx.paidById,
			}),
			mine ? exactCell(mine.shareAmount) : 0,
			// Hidden from a debtor: empty, not 0.
			theirs ? exactCell(theirs.shareAmount) : "",
			tx.projectId ? (projectName.get(tx.projectId) ?? "") : "",
			txStatus(tx.isLocked, tx.splitParticipants),
			editCounts.get(tx.id) ?? 0,
		];
	});

	const today = dayKey(new Date(), ctx.timeZone);
	const meta = csvMeta([
		"Generated by Retrospend",
		`Export Date: ${today}`,
		`Transaction History with: ${theirName}`,
		`Total Transactions: ${transactions.length}`,
		"",
	]);
	return {
		csv: meta + generateCsv(headers, rows),
		filename: `history-${slug(theirName, 30)}-${today}.csv`,
	};
}

/** What is open between the user and a person, one row per currency. */
export async function exportPersonSettlementPlan(
	ctx: ExportContext,
	them: PersonRef,
): Promise<CsvDocument> {
	const shared = await ctx.db.sharedTransaction.findMany({
		where: await sharedWith(ctx.db, them),
		select: { currency: true },
	});
	if (shared.length === 0) throw noSharedExpenses();

	const names = await resolveParticipantNames(ctx.db, [them]);
	const theirName = nameOf(names, them);
	const open = (
		await pairBalances(
			ctx.db,
			ctx.userId,
			them,
			shared.map((tx) => tx.currency),
		)
	).filter((b) => b.direction !== "settled");

	const headers = ["Currency", "Amount", "Direction"];
	const rows = open.map((b) => [
		b.currency,
		balanceText(b),
		directionText(b.direction, theirName),
	]);

	const today = dayKey(new Date(), ctx.timeZone);
	const meta = csvMeta([
		"Generated by Retrospend",
		`Export Date: ${today}`,
		`Settlement Plan with: ${theirName}`,
		"",
	]);
	return {
		csv:
			meta +
			(rows.length > 0
				? generateCsv(headers, rows)
				: "Currency,Amount,Direction\n(All settled up)\n"),
		filename: `settlement-${slug(theirName, 30)}-${today}.csv`,
	};
}
