// Design tokens: docs/ui/design.json is the source of truth. This module turns
// it into src/styles/tokens.css (web) and the generated hex values (native).
// `pnpm ui:tokens` writes both; tokens.test.ts fails when either is stale.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import {
	contrast,
	mixOklab,
	over,
	parseColor,
	type Rgba,
	toHex,
} from "./color";
import { REPO_ROOT } from "./paths";

export const DESIGN_PATH = join(REPO_ROOT, "docs/ui/design.json");
export const TOKENS_CSS_PATH = join(REPO_ROOT, "src/styles/tokens.css");

export type Theme = "light" | "dark";
export type ColorToken = {
	group: string;
	job: string;
	css?: string;
	light: string;
	dark: string;
	hex?: { light: string; dark: string };
};
type Scale = {
	size: number;
	lineHeight: number;
	weight: number;
	tracking?: number;
	use: string;
};
type Sized = { desktop?: number; phone?: number; ios?: number; use?: string };
export type Design = {
	color: Record<string, ColorToken>;
	type: { weights: number[]; scale: Record<string, Scale> };
	space: number[];
	radius: Record<string, number>;
	size: Record<string, Sized & Record<string, unknown>>;
	breakpoints: { phone: { max: number } };
	shadow: Record<string, { use: string; light: string; dark: string }>;
	motion: {
		duration: Record<string, { ms: number; use: string }>;
		easing: Record<string, { bezier: number[]; use: string }>;
	};
	[key: string]: unknown;
};

export function loadDesign(path = DESIGN_PATH): Design {
	return JSON.parse(readFileSync(path, "utf8")) as Design;
}

/** CSS custom property name of a color token (without the leading dashes). */
export function cssName(design: Design, token: string): string {
	const t = design.color[token];
	if (!t) throw new Error(`unknown color token ${token}`);
	return t.css ?? token;
}

const MIX = /^mix\(\s*([\w-]+)\s+([\d.]+)%\s*(?:,\s*([\w-]+)\s*)?\)$/;
const REF = /^ref\(\s*([\w-]+)\s*\)$/;

/** The CSS value of a token in one theme (`var()` for mixes and refs). */
export function cssValue(design: Design, token: string, theme: Theme): string {
	const t = design.color[token];
	if (!t) throw new Error(`unknown color token ${token}`);
	const v = t[theme];
	const mix = MIX.exec(v);
	if (mix) {
		const a = `var(--${cssName(design, mix[1] as string)})`;
		const b = mix[3] ? `var(--${cssName(design, mix[3])})` : "transparent";
		return `color-mix(in oklab, ${a} ${mix[2]}%, ${b})`;
	}
	const ref = REF.exec(v);
	if (ref) return `var(--${cssName(design, ref[1] as string)})`;
	return v;
}

/** Resolve a token to an sRGB color in one theme. */
export function resolve(design: Design, token: string, theme: Theme): Rgba {
	const t = design.color[token];
	if (!t) throw new Error(`unknown color token ${token}`);
	const v = t[theme];
	const mix = MIX.exec(v);
	if (mix) {
		const a = resolve(design, mix[1] as string, theme);
		const b = mix[3] ? resolve(design, mix[3], theme) : undefined;
		return mixOklab(a, Number(mix[2]), b);
	}
	const ref = REF.exec(v);
	if (ref) return resolve(design, ref[1] as string, theme);
	return parseColor(v);
}

/** Contrast of `fg` on `bg` in a theme; a translucent fg is composited first. */
export function tokenContrast(
	design: Design,
	fg: string | Rgba,
	bg: string,
	theme: Theme,
): number {
	const under = resolve(design, bg, theme);
	const top = typeof fg === "string" ? resolve(design, fg, theme) : fg;
	return contrast(over(top, under), under);
}

/** design.json with every color's `hex` filled in, as the file should read. */
export function withHex(design: Design): Design {
	const color: Record<string, ColorToken> = {};
	for (const [name, t] of Object.entries(design.color)) {
		const { hex: _old, ...rest } = t;
		color[name] = {
			...rest,
			hex: {
				light: toHex(resolve(design, name, "light")),
				dark: toHex(resolve(design, name, "dark")),
			},
		};
	}
	return { ...design, color };
}

export function formatDesign(design: Design): string {
	return `${JSON.stringify(design, null, "\t")}\n`;
}

const px = (n: number) => (n >= 999 ? "9999px" : `${n}px`);
const rem = (n: number) => `${n / 16}rem`;

/** src/styles/tokens.css, generated from design.json. */
export function buildTokensCss(design: Design): string {
	const L: string[] = [];
	const colors = Object.keys(design.color);
	const size = design.size;
	const get = (key: string, field: "desktop" | "phone") => {
		const v = size[key]?.[field];
		if (typeof v !== "number") throw new Error(`size.${key}.${field} missing`);
		return v;
	};
	L.push(
		"/*",
		" * Design tokens. GENERATED by `pnpm ui:tokens` from docs/ui/design.json.",
		" * Do not edit by hand: change design.json, run the script, commit both.",
		" * How to use each token: docs/ui/GUIDELINE.md §2. The legacy shadcn",
		" * theme in globals.css stays until the switch-over (docs/ui/GAPS.md).",
		" * The accent is --ds-accent (Tailwind `ds-accent`) until then, because",
		" * shadcn already owns --accent.",
		" */",
		"",
		":root {",
	);
	for (const c of colors)
		L.push(`\t--${cssName(design, c)}: ${cssValue(design, c, "light")};`);
	L.push(
		`\t--r-ctl: ${px(design.radius.ctl ?? 8)};`,
		`\t--r-panel: ${px(design.radius.panel ?? 12)};`,
		`\t--r-chip: ${px(design.radius.chip ?? 999)};`,
		`\t--ctl-h: ${px(get("ctl", "desktop"))};`,
		`\t--ctl-sm: ${px(get("ctl-sm", "desktop"))};`,
		`\t--row-h: ${px(get("row", "desktop"))};`,
		`\t--gutter: ${px(get("gutter", "desktop"))};`,
		`\t--trail: ${px(get("trail", "desktop"))};`,
		`\t--money-h: ${px(get("money-input", "desktop"))};`,
	);
	for (const [name, s] of Object.entries(design.shadow))
		L.push(`\t--elev-${name}: ${s.light};`);
	for (const [name, d] of Object.entries(design.motion.duration))
		L.push(`\t--t-${name}: ${d.ms}ms;`);
	L.push("}", "", ".dark {");
	for (const c of colors) {
		const t = design.color[c];
		if (t && t.dark !== t.light)
			L.push(`\t--${cssName(design, c)}: ${cssValue(design, c, "dark")};`);
	}
	for (const [name, s] of Object.entries(design.shadow)) {
		if (s.dark !== s.light) L.push(`\t--elev-${name}: ${s.dark};`);
	}
	L.push(
		"}",
		"",
		`@media (max-width: ${design.breakpoints.phone.max}px) {`,
		"\t:root {",
		`\t\t--ctl-h: ${px(get("ctl", "phone"))};`,
		`\t\t--row-h: ${px(get("row", "phone"))};`,
		`\t\t--gutter: ${px(get("gutter", "phone"))};`,
		`\t\t--trail: ${px(get("trail", "phone"))};`,
		`\t\t--money-h: ${px(get("money-input", "phone"))};`,
		"\t}",
		"}",
		"",
		"/* Reduced motion: opacity only. Movement durations drop to 1ms. */",
		"@media (prefers-reduced-motion: reduce) {",
		"\t:root {",
	);
	for (const name of Object.keys(design.motion.duration))
		L.push(`\t\t--t-${name}: 1ms;`);
	L.push("\t}", "}", "", "@theme inline {");
	for (const c of colors)
		L.push(`\t--color-${cssName(design, c)}: var(--${cssName(design, c)});`);
	L.push(
		"\t--radius-ctl: var(--r-ctl);",
		"\t--radius-panel: var(--r-panel);",
		"\t--radius-chip: var(--r-chip);",
		"\t--spacing-ctl: var(--ctl-h);",
		"\t--spacing-ctl-sm: var(--ctl-sm);",
		"\t--spacing-row: var(--row-h);",
		"\t--spacing-gutter: var(--gutter);",
		"\t--spacing-trail: var(--trail);",
		"\t--spacing-money: var(--money-h);",
	);
	for (const name of Object.keys(design.shadow))
		L.push(`\t--shadow-${name}: var(--elev-${name});`);
	L.push("}", "", "@theme {");
	for (const [name, s] of Object.entries(design.type.scale)) {
		L.push(
			`\t--text-${name}: ${rem(s.size)};`,
			`\t--text-${name}--line-height: ${s.lineHeight};`,
			`\t--text-${name}--font-weight: ${s.weight};`,
		);
		if (s.tracking)
			L.push(`\t--text-${name}--letter-spacing: ${s.tracking}em;`);
	}
	for (const [name, e] of Object.entries(design.motion.easing)) {
		L.push(`\t--ease-${name}: cubic-bezier(${e.bezier.join(", ")});`);
	}
	L.push("}", "");
	return L.join("\n");
}
