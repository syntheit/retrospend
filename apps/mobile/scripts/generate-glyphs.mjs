// Writes the drawings the app shows from the web's own sources, so a
// category or a currency looks the same on every client:
//
//   src/ui/glyphs.generated.ts  lucide shapes for the category icon keys
//                               (packages/domain/src/category-icons.ts) and a
//                               few control glyphs
//   src/ui/flags.generated.ts   the circle flags public/images/flags holds,
//                               keyed by the country code
//                               (packages/domain/src/currency-country.ts)
//
// Run after changing either list: `node apps/mobile/scripts/generate-glyphs.mjs`
// from the repo root. glyphs.test.ts fails when a key has no drawing.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const out = join(here, "..", "src", "ui");

const { CATEGORY_ICON_NAMES } = await import(
	pathToFileURL(join(root, "packages/domain/src/category-icons.ts")).href
);
const { CURRENCIES } = await import(
	pathToFileURL(join(root, "packages/domain/src/currencies.ts")).href
);
const { getCountryCodeFromCurrency } = await import(
	pathToFileURL(join(root, "packages/domain/src/currency-country.ts")).href
);

/** Glyphs the screens need beyond the category icons. */
const EXTRA_GLYPHS = ["Check", "Coins", "Search", "X"];

const lucideDir = dirname(
	createRequire(join(root, "package.json")).resolve(
		"lucide-react/package.json",
	),
);
const kebab = (name) =>
	name.replace(/([a-z])([A-Z0-9])/g, "$1-$2").toLowerCase();

/** The drawing in a lucide icon file; renamed icons are one-line re-exports of the new name. */
async function shapes(name) {
	let file = join(lucideDir, "dist/esm/icons", `${kebab(name)}.mjs`);
	const alias = readFileSync(file, "utf8").match(
		/export \{ default \} from '\.\/(.+)';/,
	);
	if (alias) file = join(dirname(file), alias[1]);
	const data = (await import(pathToFileURL(file).href)).__iconData;
	if (!data) throw new Error(`${name}: no icon data in ${file}`);
	return data.node.map(([tag, { key: _key, ...attrs }]) => [tag, attrs]);
}

const banner =
	"// Generated by apps/mobile/scripts/generate-glyphs.mjs. Do not edit.\n";

const glyphs = {};
for (const name of [...CATEGORY_ICON_NAMES, ...EXTRA_GLYPHS].sort()) {
	glyphs[name] = await shapes(name);
}
writeFileSync(
	join(out, "glyphs.generated.ts"),
	`${banner}export type GlyphShape = [tag: string, attrs: Record<string, string>];

/** lucide shapes on a 24 point grid, stroked 1.75 wide (GUIDELINE 2.7). */
export const GLYPHS: Record<string, GlyphShape[]> = ${JSON.stringify(glyphs)};
`,
);

const flags = {};
for (const code of Object.keys(CURRENCIES)) {
	const country = getCountryCodeFromCurrency(code);
	const file = country && join(root, "public/images/flags", `${country}.svg`);
	if (file && existsSync(file)) {
		flags[country] = readFileSync(file, "utf8").trim();
	}
}
writeFileSync(
	join(out, "flags.generated.ts"),
	`${banner}/** Circle flag drawings by country code, for the fiat currencies. */
export const FLAGS: Record<string, string> = ${JSON.stringify(flags)};
`,
);
console.log(
	`${Object.keys(glyphs).length} glyphs, ${Object.keys(flags).length} flags`,
);
