// Writes src/lib/currency-names.generated.ts: every fiat currency's name in
// each app language, from Node's CLDR data. Hermes has no Intl.DisplayNames,
// so without this table the phone shows English names in every language.
// English needs no table (packages/domain/src/currencies.ts has the names),
// and es-AR keeps only the names that differ from es.
//
// Run after changing the currency list or the app languages:
// `node apps/mobile/scripts/generate-currency-names.mjs` from the repo root.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const out = join(here, "..", "src", "lib", "currency-names.generated.ts");

const { CURRENCIES } = await import(
	pathToFileURL(join(root, "packages/domain/src/currencies.ts")).href
);
const { APP_LOCALES } = await import(
	pathToFileURL(join(here, "..", "src", "lib", "locales.ts")).href
);

const codes = Object.keys(CURRENCIES).sort();

function namesIn(locale) {
	const names = new Intl.DisplayNames([locale], {
		type: "currency",
		fallback: "none",
	});
	const table = {};
	for (const code of codes) {
		const name = names.of(code);
		if (name && name !== code) table[code] = name;
	}
	return table;
}

const tables = {};
for (const locale of APP_LOCALES) {
	if (locale === "en") continue;
	tables[locale] = namesIn(locale);
}
// es-AR falls back to es, so it keeps only its own differences.
if (tables["es-AR"] && tables.es) {
	for (const [code, name] of Object.entries(tables["es-AR"])) {
		if (tables.es[code] === name) delete tables["es-AR"][code];
	}
}

const body = Object.entries(tables)
	.map(([locale, table]) => {
		const rows = Object.entries(table)
			.map(([code, name]) => `\t\t${code}: ${JSON.stringify(name)},`)
			.join("\n");
		const key = /^[a-z]+$/.test(locale) ? locale : JSON.stringify(locale);
		return `\t${key}: {\n${rows}\n\t},`;
	})
	.join("\n");

writeFileSync(
	out,
	`// Generated by apps/mobile/scripts/generate-currency-names.mjs. Do not edit.

/** Currency names by app language (not English), from CLDR. */
export const CURRENCY_NAMES: Record<string, Record<string, string>> = {
${body}
};
`,
);
console.log(`wrote ${out}`);
