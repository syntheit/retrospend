// The languages the app has catalogs for. Written out here because the config
// loader cannot import from src/; test/app-config.test.ts keeps it equal to
// src/lib/locales.ts.
export const APP_LOCALES = ["en", "es", "es-AR", "ru", "pt-BR", "fr", "de"];

const DEV_PROFILES = ["development", "simulator"];
// Maestro builds (maestro-plan.md 2.2): the only profile that may carry the
// test-only sign-in link (EXPO_PUBLIC_E2E), and the dev variables too.
const E2E_PROFILE = "e2e";

/**
 * Metro bakes every EXPO_PUBLIC_* value into the JS bundle, and reads them
 * from apps/mobile/.env* too. The dev auto sign-in (a server, an email and a
 * password) and the gallery flag must never reach a release bundle, so the
 * config refuses to build with them unless the build says it is a dev or
 * simulator build (RETROSPEND_BUILD_PROFILE=development|simulator). The
 * test-only sign-in link (EXPO_PUBLIC_E2E) is stricter: only the e2e profile.
 */
export function assertBuildProfile(
	env: Record<string, string | undefined>,
): void {
	const dev = Object.keys(env).filter(
		(name) =>
			(name.startsWith("EXPO_PUBLIC_DEV_") || name === "EXPO_PUBLIC_GALLERY") &&
			env[name],
	);
	const profile = env.RETROSPEND_BUILD_PROFILE ?? "";
	if (
		dev.length > 0 &&
		!DEV_PROFILES.includes(profile) &&
		profile !== E2E_PROFILE
	) {
		throw new Error(
			`${dev.join(", ")} must not be set in a release build. Unset them, or build with RETROSPEND_BUILD_PROFILE=development or simulator.`,
		);
	}
	if (env.EXPO_PUBLIC_E2E && profile !== E2E_PROFILE) {
		throw new Error(
			"EXPO_PUBLIC_E2E must not be set in a release build. Unset it, or build with RETROSPEND_BUILD_PROFILE=e2e.",
		);
	}
}

assertBuildProfile(process.env);

/**
 * The app ships under the release version of Retrospend itself (Immich does
 * the same): the version in the repo root package.json, the one the server
 * reports. Nothing here is kept by hand. The build number below tells two
 * builds of one release apart.
 */
export function releaseVersion(
	rootPackagePath = join(__dirname, "..", "..", "package.json"),
): string {
	const { version } = JSON.parse(readFileSync(rootPackagePath, "utf8")) as {
		version?: unknown;
	};
	if (typeof version !== "string" || !/^\d+\.\d+\.\d+/.test(version)) {
		throw new Error(`${rootPackagePath} has no release version.`);
	}
	return version;
}

// Release scripts pass the commit count, so every build is newer than the
// last. A plain build is number 1.
export function buildNumber(env: Record<string, string | undefined>): number {
	// An empty value (ios-build.sh passes one on) means a plain build.
	const n = Number(env.RETROSPEND_BUILD_NUMBER || 1);
	if (!Number.isInteger(n) || n < 1) {
		throw new Error("RETROSPEND_BUILD_NUMBER must be a positive integer.");
	}
	return n;
}
const BUILD_NUMBER = buildNumber(process.env);

/**
 * The APNs environment this build's device tokens belong to. Only Xcode debug
 * builds (RETROSPEND_APNS_ENV=development, set by ios-mini.sh) use the
 * sandbox; Release archives and TestFlight builds use production, so an
 * unset variable is production.
 */
export function apnsEnvironment(
	env: Record<string, string | undefined>,
): "development" | "production" {
	return env.RETROSPEND_APNS_ENV === "development"
		? "development"
		: "production";
}
const APNS_ENV = apnsEnvironment(process.env);

/** The server the connect screen starts on; empty when the build names none. */
export function defaultServer(env: Record<string, string | undefined>): string {
	return (env.RETROSPEND_DEFAULT_SERVER ?? "").trim();
}

/**
 * The servers the app is tied to as its own: universal links (iOS) and app
 * links (Android) open the app for these hosts only. A self-hosted server on
 * another domain cannot be verified in advance, so its links open the
 * browser. WEB_LINK_PATHS is the first path segments the app has screens for;
 * src/surfaces/links.ts holds the same lists and test/app-config.test.ts
 * keeps them equal.
 */
export const LINK_HOSTS = ["retrospend.app", "dev.retrospend.app"];
export const WEB_LINK_PATHS = [
	"projects",
	"people",
	"entries",
	"notifications",
	"home",
	"activity",
	"budget",
	"wealth",
];

/**
 * The iOS associated domains. Universal links (applinks) are off by default:
 * the entitlement fails signing and upload until the Associated Domains
 * capability is enabled for the App ID in the Apple developer portal. Set
 * RETROSPEND_IOS_APPLINKS=1 once it is. Android app links are not affected.
 */
export function associatedDomains(
	env: Record<string, string | undefined>,
): string[] {
	return [
		...LINK_HOSTS.map((host) => `webcredentials:${host}`),
		...(env.RETROSPEND_IOS_APPLINKS === "1"
			? LINK_HOSTS.map((host) => `applinks:${host}`)
			: []),
	];
}

