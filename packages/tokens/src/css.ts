// src/styles/tokens.css: CSS variables plus the Tailwind v4 @theme entries
// that turn them into utilities (bg-surface, h-ctl, rounded-panel, text-title).
// References in the source become var(--x), so a mix follows its inputs when
// the theme changes.
import type { TransformedToken } from "style-dictionary/types";
import {
	darkOverrides,
	type Dimension,
	type ShadowLayer,
	type Theme,
	type Tokens,
} from "./load";

/** Size tokens that are CSS variables and Tailwind spacing utilities. */
const SIZES = [
	{ token: "ctl", cssVar: "ctl-h", utility: "ctl" },
	{ token: "ctl-sm", cssVar: "ctl-sm", utility: "ctl-sm" },
	{ token: "row", cssVar: "row-h", utility: "row" },
	{ token: "gutter", cssVar: "gutter", utility: "gutter" },
	{ token: "trail", cssVar: "trail", utility: "trail" },
	{ token: "money-input", cssVar: "money-h", utility: "money" },
];

const HEADER = `/*
 * Design tokens. GENERATED by \`pnpm ui:tokens\` from packages/tokens/src.
 * Do not edit by hand: change the token JSON, run the script, commit both.
 * How to use each token: docs/ui/GUIDELINE.md §2. The legacy shadcn
 * theme in globals.css stays until the switch-over (docs/ui/GAPS.md).
 * The accent is --ds-accent (Tailwind \`ds-accent\`) until then, because
 * shadcn already owns --accent.
 */
`;

const leaf = (t: TransformedToken) => t.path.at(-1) as string;
const group = (tokens: Tokens, name: string) =>
	[...tokens.values()].filter((t) => t.path[0] === name);

function cssName(t: TransformedToken): string {
	const ext = t.$extensions?.["app.retrospend"] as
		| { cssName?: string }
		| undefined;
	return ext?.cssName ?? leaf(t);
}

const dimension = (d: Dimension) =>
	d.value === 0 ? "0" : `${d.value}${d.unit}`;

/** Lookups and value formatting over the light tokens (the CSS defaults). */
function formatters(light: Tokens) {
	const colors = group(light, "color");
	const varOf = new Map(colors.map((t) => [t.path.join("."), cssName(t)]));
	// A source value with its {references} written as var(--x).
	const withVars = (value: string) =>
		value.replace(/\{([\w.-]+)\}/g, (_, path: string) => {
			const name = varOf.get(path);
			if (!name) throw new Error(`no CSS variable for {${path}}`);
			return `var(--${name})`;
		});
	const shadow = (t: TransformedToken) =>
		(t.original.$value as ShadowLayer[])
			.map((l) =>
				[
					dimension(l.offsetX),
					dimension(l.offsetY),
					dimension(l.blur),
					...(l.spread.value === 0 ? [] : [dimension(l.spread)]),
					withVars(l.color),
				].join(" "),
			)
			.join(", ");
	const value = (path: string) => {
		const t = light.get(path);
		if (!t) throw new Error(`token ${path} missing`);
		return t.$value;
	};
	const size = (token: string, screen: "desktop" | "phone") =>
		dimension(value(`size.${token}.${screen}`));
	return { colors, withVars, shadow, value, size };
}

export function tokensCss({ light, dark }: Record<Theme, Tokens>): string {
	const { colors, withVars, shadow, value, size } = formatters(light);
	const durations = group(light, "duration");
	const overrides = darkOverrides(dark);

	const L: string[] = [HEADER, ":root {"];
	for (const t of colors)
		L.push(`\t--${cssName(t)}: ${withVars(t.original.$value as string)};`);
	for (const t of group(light, "radius"))
		L.push(`\t--r-${leaf(t)}: ${dimension(t.$value)};`);
	for (const s of SIZES)
		L.push(`\t--${s.cssVar}: ${size(s.token, "desktop")};`);
	for (const t of group(light, "shadow"))
		L.push(`\t--elev-${leaf(t)}: ${shadow(t)};`);
	for (const t of durations)
		L.push(`\t--t-${leaf(t)}: ${dimension(t.$value)};`);

	L.push("}", "", ".dark {");
	for (const t of overrides.filter((t) => t.path[0] === "color"))
		L.push(`\t--${cssName(t)}: ${withVars(t.original.$value as string)};`);
	for (const t of overrides.filter((t) => t.path[0] === "shadow"))
		L.push(`\t--elev-${leaf(t)}: ${shadow(t)};`);

	const phoneMax: Dimension = value("breakpoint.phone.max");
	L.push("}", "", `@media (max-width: ${dimension(phoneMax)}) {`, "\t:root {");
	for (const s of SIZES) {
		const phone = size(s.token, "phone");
		if (phone !== size(s.token, "desktop"))
			L.push(`\t\t--${s.cssVar}: ${phone};`);
	}
	L.push(
		"\t}",
		"}",
		"",
		"/* Reduced motion: opacity only. Movement durations drop to 1ms. */",
		"@media (prefers-reduced-motion: reduce) {",
		"\t:root {",
	);
	for (const t of durations) L.push(`\t\t--t-${leaf(t)}: 1ms;`);

	L.push("\t}", "}", "", "@theme inline {");
	for (const t of colors)
		L.push(`\t--color-${cssName(t)}: var(--${cssName(t)});`);
	for (const t of group(light, "radius"))
		L.push(`\t--radius-${leaf(t)}: var(--r-${leaf(t)});`);
	for (const s of SIZES)
		L.push(`\t--spacing-${s.utility}: var(--${s.cssVar});`);
	for (const t of group(light, "shadow"))
		L.push(`\t--shadow-${leaf(t)}: var(--elev-${leaf(t)});`);

	L.push("}", "", "@theme {");
	for (const name of new Set(group(light, "type").map((t) => t.path[1]))) {
		const fontSize: Dimension = value(`type.${name}.size`);
		L.push(
			`\t--text-${name}: ${fontSize.value / 16}rem;`,
			`\t--text-${name}--line-height: ${value(`type.${name}.line-height`)};`,
			`\t--text-${name}--font-weight: ${value(`type.${name}.weight`)};`,
		);
		const tracking = light.get(`type.${name}.tracking`);
		if (tracking)
			L.push(`\t--text-${name}--letter-spacing: ${tracking.$value}em;`);
	}
	for (const t of group(light, "easing"))
		L.push(
			`\t--ease-${leaf(t)}: cubic-bezier(${(t.$value as number[]).join(", ")});`,
		);
	L.push("}", "");
	return L.join("\n");
}
