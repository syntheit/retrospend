// Resolved token values for clients that cannot use CSS: dist/theme.ts for
// React Native and dist/tokens.json (flat) for anything else. Colors become
// sRGB hex, sizes plain numbers (dp or pt), durations milliseconds.
import type { TransformedToken } from "style-dictionary/types";
import { parseColor, toHex } from "./color";
import type { Dimension, ShadowLayer, Theme, Tokens } from "./load";

const hex = (css: string) => toHex(parseColor(css));

function amount(d: Dimension, unit: "px" | "ms"): number {
	if (d.unit !== unit) throw new Error(`expected ${unit}, got ${d.unit}`);
	return d.value;
}

function nativeValue(t: TransformedToken): unknown {
	switch (t.$type) {
		case "color":
			return hex(t.$value);
		case "dimension":
			return amount(t.$value, "px");
		case "duration":
			return amount(t.$value, "ms");
		case "shadow":
			return (t.$value as ShadowLayer[]).map((l) => ({
				color: hex(l.color),
				offsetX: amount(l.offsetX, "px"),
				offsetY: amount(l.offsetY, "px"),
				blur: amount(l.blur, "px"),
				spread: amount(l.spread, "px"),
			}));
		default:
			return t.$value;
	}
}

/** One theme as a flat map: "color.bg" -> "#f4efea". */
function flat(tokens: Tokens): Record<string, unknown> {
	return Object.fromEntries(
		[...tokens].map(([path, t]) => [path, nativeValue(t)]),
	);
}

const camel = (key: string) =>
	key.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

/** The flat map as nested objects with camelCase keys: color.lineStrong. */
function nested(values: Record<string, unknown>): Record<string, unknown> {
	const root: Record<string, unknown> = {};
	for (const [path, value] of Object.entries(values)) {
		const keys = path.split(".").map(camel);
		let node = root;
		for (const key of keys.slice(0, -1)) {
			node[key] ??= {};
			node = node[key] as Record<string, unknown>;
		}
		node[keys.at(-1) as string] = value;
	}
	return root;
}

export function tokensJson(themes: Record<Theme, Tokens>): string {
	const out = {
		$description:
			"GENERATED by `pnpm ui:tokens` from packages/tokens/src. Resolved values per theme: colors are sRGB hex (#rrggbb or #rrggbbaa), sizes px (dp or pt on native), durations ms, type tracking em.",
		light: flat(themes.light),
		dark: flat(themes.dark),
	};
	return `${JSON.stringify(out, null, "\t")}\n`;
}

export function themeTs(themes: Record<Theme, Tokens>): string {
	const object = (tokens: Tokens) =>
		JSON.stringify(nested(flat(tokens)), null, "\t");
	return [
		"// GENERATED by `pnpm ui:tokens` from packages/tokens/src. Do not edit by hand.",
		"// The React Native theme: colors are sRGB hex, sizes dp or pt, durations ms,",
		"// type tracking em (multiply by the font size for letterSpacing).",
		"",
		`export const light = ${object(themes.light)};`,
		"",
		"export type Theme = typeof light;",
		"",
		`export const dark: Theme = ${object(themes.dark)};`,
		"",
	].join("\n");
}
